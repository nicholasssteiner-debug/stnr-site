// Grupo da DRE ao qual cada conta de resultado pertence (por prefixo de código)
const DRE_RULES = [
    ['3.1', 'receitaBruta'],
    ['3.2', 'deducoes'],
    ['3.3', 'resultadoFinanceiro'],
    ['3.4', 'outrasReceitasDespesas'],
    ['4.1', 'custos'],
    ['4.2.05', 'resultadoFinanceiro'],
    ['4.2', 'despesasOperacionais'],
    ['4.3', 'outrasReceitasDespesas'],
    ['4.4', 'impostosResultado'],
];

const hasChildIn = (code, accounts) => accounts.some(a => a.code.startsWith(code + '.'));

export const dreGroupFor = (code) => {
    const rule = DRE_RULES.find(([prefix]) => code === prefix || code.startsWith(prefix + '.'));
    return rule ? rule[1] : null;
};

// Monta o dreConfig (lista de contas analíticas por grupo) para um plano de contas.
export const buildDreConfig = (accounts, groupIds) => {
    const config = {};
    for (const id of groupIds) config[id] = [];
    for (const acc of accounts) {
        if (acc.type !== 'Receita' && acc.type !== 'Despesa') continue;
        if (hasChildIn(acc.code, accounts)) continue;
        const group = dreGroupFor(acc.code);
        if (group && config[group]) config[group].push(acc.code);
    }
    return config;
};

// Verificação de integridade (usada nos testes e no import): retorna lista de problemas.
export const validateChart = (accounts) => {
    const problems = [];
    const byCode = new Map();
    for (const a of accounts) {
        if (!/^\d+(\.\d+)*$/.test(a.code)) problems.push(`Código inválido: ${a.code}`);
        if (byCode.has(a.code)) problems.push(`Código duplicado: ${a.code}`);
        byCode.set(a.code, a);
        if (!a.name?.trim()) problems.push(`Conta sem nome: ${a.code}`);
    }
    for (const a of accounts) {
        if (!a.code.includes('.')) continue;
        const parentCode = a.code.slice(0, a.code.lastIndexOf('.'));
        const parent = byCode.get(parentCode);
        if (!parent) problems.push(`Conta ${a.code} sem pai (${parentCode})`);
        else if (parent.type !== a.type) problems.push(`Tipo de ${a.code} (${a.type}) difere do pai ${parentCode} (${parent.type})`);
    }
    return problems;
};
